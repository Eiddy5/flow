package org.flow.plugin.core.storage;

import java.net.URI;
import java.util.NoSuchElementException;

import org.flow.plugin.api.annotations.Example;
import org.flow.plugin.api.annotations.Plugin;
import org.flow.plugin.api.annotations.PluginProperty;
import org.flow.core.models.property.Property;
import org.flow.core.models.tasks.RunnableTask;
import org.flow.core.models.tasks.Task;
import org.flow.core.runners.RunContext;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import lombok.*;
import lombok.experimental.SuperBuilder;

@SuperBuilder
@ToString
@EqualsAndHashCode
@Getter
@NoArgsConstructor
@Schema(
    title = "Delete a file from Flow internal storage.",
    description = """
        Removes the file at the given `flow://` URI. If `errorOnMissing` is true and the file doesn’t exist, the task fails.

        Useful for cleaning temp artifacts after merges/downloads."""
)
@Plugin(
    examples = {
        @Example(
            title = "Delete a file generated by another task.",
            full = true,
            code = """
                    id: delete_files
                    namespace: company.team

                    tasks:
                      - id: download
                        type: org.flow.plugin.core.http.Download
                        uri: https://example.com/orders.csv

                      - id: delete
                        type: org.flow.plugin.core.storage.Delete
                        uri: "{{ outputs.download.uri }}"
                """
        )
    }
)
public class Delete extends Task implements RunnableTask<Delete.Output> {
    @Schema(
        title = "The file to be deleted"
    )
    @NotNull
    @PluginProperty(internalStorageURI = true)
    private Property<String> uri;

    @Schema(
        title = "Raise an error if the file is not found"
    )
    @Builder.Default
    private final Property<Boolean> errorOnMissing = Property.ofValue(false);

    @Override
    public Delete.Output run(RunContext runContext) throws Exception {
        URI render = URI.create(runContext.render(this.uri).as(String.class).orElseThrow());

        boolean delete = runContext.storage().deleteFile(render);

        if (runContext.render(errorOnMissing).as(Boolean.class).orElseThrow() && !delete) {
            throw new NoSuchElementException("Unable to find file '" + render + "'");
        }

        return Output.builder()
            .uri(render)
            .deleted(delete)
            .build();
    }

    @Builder
    @Getter
    public static class Output implements org.flow.core.models.tasks.Output {
        @Schema(
            title = "The deleted file URI"
        )
        private final URI uri;

        @Schema(
            title = "A flag for whether the file was deleted"
        )
        private final Boolean deleted;
    }
}
