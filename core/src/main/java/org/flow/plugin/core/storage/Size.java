package org.flow.plugin.core.storage;

import java.net.URI;

import org.flow.plugin.api.annotations.Example;
import org.flow.plugin.api.annotations.Plugin;
import org.flow.plugin.api.annotations.PluginProperty;
import org.flow.core.models.property.Property;
import org.flow.core.models.tasks.RunnableTask;
import org.flow.core.models.tasks.Task;
import org.flow.core.runners.RunContext;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import lombok.*;
import lombok.experimental.SuperBuilder;

@SuperBuilder
@ToString
@EqualsAndHashCode
@Getter
@NoArgsConstructor
@Schema(
    title = "Get the size of a file in Flow internal storage.",
    description = "Reads the file attributes for the given `flow://` URI and returns its size in bytes."
)
@Plugin(
    examples = {
        @Example(
            title = "Get the size of a text file generated by another task.",
            full = true,
            code = """
                    id: get_file_size
                    namespace: company.team

                    tasks:
                      - id: generate_file
                        type: org.flow.plugin.scripts.shell.Commands
                        commands:
                          - echo "Hello John" > name.txt
                        outputFiles:
                          - "name.txt"

                      - id: get_size
                        type: org.flow.plugin.core.storage.Size
                        uri: "{{ outputs.generate_file.outputFiles['name.txt'] }}"

                      - id: log
                        type: org.flow.plugin.core.log.Log
                        message: "{{ outputs.get_size.size }} bytes"
                """
        )
    }
)
public class Size extends Task implements RunnableTask<Size.Output> {
    @Schema(
        title = "The file where size needs to be fetched"
    )
    @NotNull
    @PluginProperty(internalStorageURI = true)
    private Property<String> uri;

    @Override
    public Size.Output run(RunContext runContext) throws Exception {
        URI render = URI.create(runContext.render(this.uri).as(String.class).orElseThrow());

        Long size = runContext.storage().getAttributes(render).getSize();

        return Output.builder()
            .size(size)
            .build();
    }

    @Builder
    @Getter
    public static class Output implements org.flow.core.models.tasks.Output {
        @Schema(
            title = "The size of the file in bytes"
        )
        private final Long size;
    }
}
